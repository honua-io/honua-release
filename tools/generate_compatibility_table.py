"""Render customer compatibility documentation from a release lock, without certification inference."""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml

from sdk_baselines import SDK_COMPONENTS, check_component, content_digest, findings, release_context
from validate_platform_lock import validate
from verify_sdk_baseline_sources import SourceReader, verify_sources

ROOT = Path(__file__).resolve().parents[1]


def cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").replace("\r", " ")


UNQUALIFIED_EDGE = ("unqualified",) * 4


def upgrade_edges(lock: dict, context: dict) -> list[str]:
    """Upgrade-edge rows from facts the lock pins; every other column is explicitly unqualified.

    Until an edge has separate schema-read and database-recovery receipts, a generic rollback
    pass cannot establish either capability, so no row claims one. The only edge the lock can
    state is the one into the first release: the pinned publication-history receipt (verified
    live by --check) says no earlier server exists, so that release is a fresh install and has
    no previous server to roll back to.
    """
    server = (lock.get("components") or {}).get("honua-server") or {}
    database = (server.get("schemaVersions") or {}).get("database")
    version = context.get("firstReleaseVersion")
    # Same binding as first_release_floor: a version no locked server artifact carries names a
    # server nobody can install, so it is not stated as an edge endpoint.
    if not any(isinstance(artifact, dict) and artifact.get("version") == version
               for artifact in server.get("artifacts") or []):
        version = None
    target = (f"{version} / database schema {database}" if version and database
              else "unqualified")
    history = context.get("publicationHistory")
    rows = []
    if isinstance(history, dict) and history.get("sha256") and history.get("uri") and version:
        rows.append(("none: honua-server has no earlier release", target,
                     "fresh install only; no upgrade edge into the first release exists",
                     "not applicable: no previous server", "not applicable", "not applicable",
                     f"Publication-history receipt `{history['sha256']}` ({history['uri']})"))
    else:
        reason = ("No locked honua-server artifact carries the first release version" if version is None
                  else "No first-release publication history is pinned in this lock")
        rows.append(("unqualified", target, *UNQUALIFIED_EDGE, reason))
    rows.append(("pre-release build (nightly or earlier candidate)", target, *UNQUALIFIED_EDGE,
                 "No edge receipt is pinned; pre-release builds are not release identities"))
    rows.append((target, "next honua-server release", *UNQUALIFIED_EDGE,
                 "No later release is locked; each column needs its own receipt"))
    return ["| " + " | ".join(cell(value) for value in row) + " |" for row in rows]


def render(lock: dict) -> str:
    context = release_context(lock)
    lines = [
        "# SDK and server compatibility", "",
        "<!-- Generated by tools/generate_compatibility_table.py; do not edit. -->", "",
        f"Platform: `{cell(lock.get('platform', {}).get('id', 'unqualified'))}`. "
        f"Lock canonical SHA-256: `{content_digest(lock)}`.", "",
        "Lock completeness: " + ("validated; certification still requires receipts." if validate(lock).ok else "**unqualified — incomplete draft; not a certified release lock.**"), "",
        "This table reports declared protocol requirements. A version floor is not a certified",
        "SDK/server pairing. Certification requires an exact artifact-pair receipt in the compatibility ledger.", "",
        "[Derivation rule](SDK-SERVER-BASELINE-RULE.md). Missing evidence is explicitly unqualified.", "",
        "| SDK / protocol | Locked artifact | Minimum server | Qualification |",
        "| --- | --- | --- | --- |",
    ]
    if str(lock.get("platform", {}).get("id", "")).startswith("honua-2026.1"):
        lines[4:4] = ["2026.1 uses `Licensing__Mode=Disabled`: all catalog entitlements active; no edition gating,",
                      "license enforcement or serving-unit metering. Maturity and safety limits still apply.", ""]
    for name in SDK_COMPONENTS:
        component = lock.get("components", {}).get(name, {})
        artifacts = "; ".join(f"{a.get('coordinate', 'unqualified')} {a.get('version', 'unqualified')}" for a in component.get("artifacts", [])) or "source pin only"
        try:
            floor, qualification = check_component(component, context), "declared floor; pairing unqualified"
        except (ValueError, TypeError, KeyError, AttributeError) as exc:
            floor, qualification = "unqualified", str(exc)
        lines.append(f"| {cell(name)} | {cell(artifacts)} | {cell(floor)} | {cell(qualification)} |")
    lines += [
        "", "The JavaScript repository also owns `@honua/mcp-server`; its Honua attachment must",
        "bind the consumed SDK and MCP manifests. Standalone third-party protocol reads do not",
        "require a Honua Server. `geospatial-mcp` is the protocol specification, not an SDK binary.",
        "", "## UPGRADE EDGES", "",
        "| From server / schema | To server / schema | Supported edge | Previous server reads migrated schema / application rollback | Database rollback | Restore backup required | Evidence |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    lines += upgrade_edges(lock, context)
    lines += [
        "", "Application rollback reinstalls the previous server against the migrated database.",
        "Database rollback restores the previous schema and data state. They require separate evidence.",
        "If the previous server cannot read the migrated schema and no verified database reverse",
        "migration exists, restoring a verified pre-upgrade backup is required to return to that server.",
        "A forward migration or a generic rollback receipt alone does not establish either rollback path.",
        "No supported upgrade edge is implied by adjacent version numbers or platform labels.", "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("lock", type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "docs/SDK-SERVER-COMPATIBILITY.md")
    parser.add_argument("--check", action="store_true", help="fail for stale output or any unqualified/disagreeing baseline")
    parser.add_argument("--check-output", action="store_true", help="check documentation freshness only; not a release qualification gate")
    parser.add_argument("--source-root", type=Path, help="offline git sources at ROOT/OWNER/REPO for --check; otherwise query GitHub")
    args = parser.parse_args(argv)
    try:
        lock = yaml.safe_load(args.lock.read_text(encoding="utf-8"))
        if not isinstance(lock, dict) or lock.get("lockVersion") != "platform-lock.v1":
            raise ValueError("expected a platform-lock.v1 mapping")
        output = render(lock)
        if args.check or args.check_output:
            if not args.output.exists() or args.output.read_text(encoding="utf-8") != output:
                raise ValueError("compatibility table is stale; regenerate from this lock")
        else:
            args.output.write_text(output, encoding="utf-8", newline="\n")
        errors = findings(lock)
        if args.check and errors:
            raise ValueError("; ".join(errors))
        if args.check:
            verify_sources(lock, SourceReader(args.source_root))
        print("PASS: documentation matches lock" if args.check_output else ("UNQUALIFIED: table written; use --check for release qualification" if errors else "PASS: declared baselines match lock"))
        return 0
    except (OSError, ValueError, TypeError, KeyError, AttributeError, yaml.YAMLError) as exc:
        print(f"BLOCKED: {exc}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
